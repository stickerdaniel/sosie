#[derive(Debug)]
pub(crate) struct Bitmap {
    pub w: u32,
    pub h: u32,
    pub left: i32,
    pub top: i32,
    pub data: Vec<u8>,
}

impl Bitmap {
    fn bytes(&self) -> usize {
        self.data.len() + std::mem::size_of::<Bitmap>()
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Hash)]
struct Key {
    face: u16,
    glyph: u32,
    size: u32,
    fx: u8,
}

const SUBPIXEL: f32 = 4.0;

pub(crate) fn quantize(v: f32) -> f32 {
    if v.is_finite() {
        (v * SUBPIXEL).round() / SUBPIXEL
    } else {
        v
    }
}

fn subpixel(v: f32) -> u8 {
    let f = v - v.floor();
    (f * SUBPIXEL).round() as u8 % SUBPIXEL as u8
}

const CACHE_BYTES: usize = 12 << 20;

struct Cache {
    map: HashMap<Key, Arc<Bitmap>>,
    bytes: usize,
}

fn cache() -> &'static Mutex<Cache> {
    static CACHE: OnceLock<Mutex<Cache>> = OnceLock::new();
    CACHE.get_or_init(|| {
        Mutex::new(Cache {
            map: HashMap::new(),
            bytes: 0,
        })
    })
}

pub(crate) fn bitmap(face: &Face, glyph: u32, size: f32, xq: f32) -> Option<Arc<Bitmap>> {
    if !size.is_finite() || size <= 0.0 || !xq.is_finite() {
        return None;
    }
    let key = Key {
        face: face.id,
        glyph,
        size: (size * 64.0).round().clamp(1.0, u32::MAX as f32) as u32,
        fx: subpixel(xq),
    };
    {
        let cache = cache().lock().unwrap_or_else(|e| e.into_inner());
        if let Some(b) = cache.map.get(&key) {
            return Some(b.clone());
        }
    }
    let bmp = Arc::new(rasterize(
        face,
        glyph,
        key.size as f32 / 64.0,
        key.fx as f32 / SUBPIXEL,
    )?);
    let mut cache = cache().lock().unwrap_or_else(|e| e.into_inner());
    if cache.bytes + bmp.bytes() > CACHE_BYTES {
        cache.map.clear();
        cache.bytes = 0;
    }
    cache.bytes += bmp.bytes();
    cache.map.insert(key, bmp.clone());
    Some(bmp)
}

pub(crate) fn outline_path(face: &Face, glyph: u32, size: f32) -> Option<tiny_skia::Path> {
    let font = face.font_ref();
    let glyphs = font.outline_glyphs();
    let drawn = glyphs.get(skrifa::GlyphId::new(glyph)).and_then(|g| {
        let mut pen = Pen::new();
        g.draw(
            DrawSettings::unhinted(Size::new(size), LocationRef::default()),
            &mut pen,
        )
        .ok()?;
        pen.finish()
    });
    if drawn.is_some() {
        return drawn;
    }
    if glyph == 0 {
        return synthetic_notdef(&font, size);
    }
    None
}

fn synthetic_notdef(font: &skrifa::FontRef<'_>, size: f32) -> Option<tiny_skia::Path> {
    let adv = font
        .glyph_metrics(Size::new(size), LocationRef::default())
        .advance_width(skrifa::GlyphId::new(0))
        .unwrap_or(0.55 * size)
        .max(0.45 * size);
    let pad_x = (0.09 * adv).max(0.75);
    let x0 = pad_x;
    let x1 = (adv - pad_x).max(x0 + 2.0);
    let y0 = -0.71 * size;
    let y1 = -0.02 * size;
    let stroke = (0.065 * size).clamp(1.0, ((x1 - x0).min(y1 - y0) * 0.35).max(1.0));

    let mut pb = PathBuilder::new();
    pb.move_to(x0, y0);
    pb.line_to(x1, y0);
    pb.line_to(x1, y1);
    pb.line_to(x0, y1);
    pb.close();
    let (ix0, iy0, ix1, iy1) = (x0 + stroke, y0 + stroke, x1 - stroke, y1 - stroke);
    if ix1 > ix0 && iy1 > iy0 {
        pb.move_to(ix0, iy0);
        pb.line_to(ix0, iy1);
        pb.line_to(ix1, iy1);
        pb.line_to(ix1, iy0);
        pb.close();
    }
    pb.finish()
}

struct Pen {
    p: PathBuilder,
    open: bool,
    any: bool,
}

const SNAP_Y: f32 = 4.0;
const FLATTEN_SHIFT_AA: i32 = 2;

fn snap_y(y: f32) -> f32 {
    (y * SNAP_Y).round() / SNAP_Y
}

fn quad_shift(dx: i32, dy: i32) -> i32 {
    let (dx, dy) = (dx.abs(), dy.abs());
    let dist = if dx > dy {
        dx + (dy >> 1)
    } else {
        dy + (dx >> 1)
    };
    let dist = (dist + (1 << 4)) >> (3 + FLATTEN_SHIFT_AA);
    (32 - (dist as u32).leading_zeros() as i32) >> 1
}

impl Pen {
    fn new() -> Pen {
        Pen {
            p: PathBuilder::new(),
            open: false,
            any: false,
        }
    }

    fn finish(mut self) -> Option<tiny_skia::Path> {
        if self.open {
            self.p.close();
        }
        if !self.any {
            return None;
        }
        self.p.finish()
    }

    fn flat_quad(&mut self, p0: (f32, f32), p1: (f32, f32), p2: (f32, f32)) {
        let fd = |v: f32| (v * 256.0).round() as i32;
        let dx = (2 * fd(p1.0) - fd(p0.0) - fd(p2.0)) >> 2;
        let dy = (2 * fd(p1.1) - fd(p0.1) - fd(p2.1)) >> 2;
        let n = 1 << quad_shift(dx, dy).clamp(1, 6);
        for i in 1..=n {
            let t = i as f32 / n as f32;
            let u = 1.0 - t;
            self.p.line_to(
                u * u * p0.0 + 2.0 * u * t * p1.0 + t * t * p2.0,
                snap_y(u * u * p0.1 + 2.0 * u * t * p1.1 + t * t * p2.1),
            );
        }
    }
}

impl OutlinePen for Pen {
    fn move_to(&mut self, x: f32, y: f32) {
        if self.open {
            self.p.close();
        }
        self.p.move_to(x, snap_y(-y));
        self.open = true;
        self.any = true;
    }
    fn line_to(&mut self, x: f32, y: f32) {
        self.p.line_to(x, snap_y(-y));
    }
    fn quad_to(&mut self, cx: f32, cy: f32, x: f32, y: f32) {
        let Some(p0) = self.p.last_point() else {
            return;
        };
        let (x0, y0, x1, y1, x2, y2) = (p0.x, p0.y, cx, -cy, x, -y);
        let den = y0 - 2.0 * y1 + y2;
        let t = if den != 0.0 { (y0 - y1) / den } else { -1.0 };
        if t > 0.0 && t < 1.0 {
            let lerp = |a: f32, b: f32| a + (b - a) * t;
            let (ax, ay) = (lerp(x0, x1), lerp(y0, y1));
            let (bx, by) = (lerp(x1, x2), lerp(y1, y2));
            let (mx, my) = (lerp(ax, bx), lerp(ay, by));
            self.flat_quad((x0, y0), (ax, my), (mx, my));
            self.flat_quad((mx, my), (bx, my), (x2, y2));
        } else {
            self.flat_quad((x0, y0), (x1, y1), (x2, y2));
        }
    }
    fn curve_to(&mut self, cx0: f32, cy0: f32, cx1: f32, cy1: f32, x: f32, y: f32) {
        self.p.cubic_to(cx0, -cy0, cx1, -cy1, x, -y);
    }
    fn close(&mut self) {
        self.p.close();
        self.open = false;
    }
}

fn rasterize(face: &Face, glyph: u32, size: f32, fx: f32) -> Option<Bitmap> {
    let path = outline_path(face, glyph, size)?;
    let bounds = path.bounds();
    let left = (bounds.left() + fx).floor();
    let top = bounds.top().floor();
    let w = ((bounds.right() + fx).ceil() - left).max(0.0) as u32;
    let h = (bounds.bottom().ceil() - top).max(0.0) as u32;
    if w == 0 || h == 0 || w > 4096 || h > 4096 {
        return None;
    }
    let data = coverage::mask_small(&path, w, h, FillRule::Winding, left - fx, top)?;
    Some(Bitmap {
        w,
        h,
        left: left as i32,
        top: top as i32,
        data,
    })
}

